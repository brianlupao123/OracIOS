/**
 * Scoped Quotation PDF Email Service
 *
 * Implements the scoped quotation-PDF email dispatch action:
 *  1. Verifies caller role/permission (Admin or Sales).
 *  2. Enforces strict recipient allowlist gating (CONTROLLED_RECIPIENT_ALLOWLIST).
 *  3. Generates the real, controlled quotation PDF buffer via pdfGenerator.js.
 *  4. Encodes and attaches the PDF to the RFC 5322 MIME message via communicationTransportService.
 *  5. Records durable communication evidence in communication_evidence with the PDF SHA-256 digest.
 */

import crypto from "node:crypto";
import { roles, requirePermission } from "../permissions.js";
import { generateControlledPdf, humanizeTimestamp, formatCurrency } from "../pdfGenerator.js";
import { sendEmail, isRecipientPermitted } from "./communicationTransportService.js";
import { recordCommunicationEvidence } from "./communicationAuditService.js";

const FALLBACK_COMPANY = { name: "Orac Systems", legalName: "Handon Enterprises (Pvt) Ltd" };
const CONTROLLED_NOTE = "Controlled record generated by Orac-IOS. Not valid if altered outside the system.";

function fromCents(cents) {
  return Number.isInteger(cents) ? cents / 100 : 0;
}

/**
 * Builds the controlled PDF model for a quotation record.
 */
export function buildQuotePdfModel(db, quoteId) {
  const quote = db.quotes?.find((q) => q.id === quoteId);
  if (!quote) return null;

  const client = db.clients?.find((c) => c.id === quote.client_id);
  const lines = db.quote_lines?.filter((l) => l.quotation_id === quote.id) || [];
  const equipment = db.equipment_tags?.find((e) => e.id === quote.equipment_tag_id);
  const companyProfile = db.company_profile || {};

  // Build work package grouped lines
  const workPackages = quote.work_packages || [];
  const wpMap = new Map(workPackages.map((wp) => [wp.id, wp.title || wp.name || wp.id]));

  const linesByWp = new Map();
  for (const line of lines) {
    const wpId = line.work_package_id || "wp_01";
    if (!linesByWp.has(wpId)) linesByWp.set(wpId, []);
    linesByWp.get(wpId).push(line);
  }

  const sections = [];

  // Site Reference
  sections.push({
    type: "keyvalue",
    heading: "Site Reference",
    items: [{ label: "Location", value: client?.name || "Client Site" }]
  });

  if (quote.scope_summary) {
    sections.push({
      type: "paragraph",
      heading: "Scope of Work",
      text: quote.scope_summary
    });
  }

  const QUOTE_LINE_COLUMNS = [
    { label: "Type", weight: 1 },
    { label: "Role / Resource", weight: 1.5 },
    { label: "Description", weight: 3 },
    { label: "Qty", weight: 0.7, align: "right" },
    { label: "UoM", weight: 0.8 },
    { label: "Rate (USD)", weight: 1.2, align: "right" },
    { label: "Total (USD)", weight: 1.2, align: "right" }
  ];

  for (const [wpId, wpLines] of linesByWp) {
    const wpName = wpMap.get(wpId) || wpId;
    const rows = wpLines.map((l) => {
      const unitPrice = Number.isInteger(l.unit_price_cents) ? fromCents(l.unit_price_cents) : Number(l.unit_price || 0);
      const lineTotal = Number.isInteger(l.line_total_cents) ? fromCents(l.line_total_cents) : Number(l.line_total ?? (Number(l.quantity) || 0) * unitPrice);
      return [
        l.cost_type || "material",
        l.resource_role || "-",
        l.description || "",
        String(l.quantity ?? ""),
        l.unit_of_measure || "each",
        formatCurrency(unitPrice),
        formatCurrency(lineTotal)
      ];
    });

    const wpSubtotalCents = wpLines.reduce((sum, l) => {
      if (Number.isInteger(l.line_total_cents)) return sum + l.line_total_cents;
      const unitPrice = Number.isInteger(l.unit_price_cents) ? fromCents(l.unit_price_cents) : Number(l.unit_price || 0);
      const lineTotal = Number(l.line_total ?? (Number(l.quantity) || 0) * unitPrice);
      return sum + Math.round(lineTotal * 100);
    }, 0);

    sections.push({
      type: "table",
      heading: linesByWp.size > 1 ? `Work Package: ${wpName}` : "Line Items",
      columns: QUOTE_LINE_COLUMNS,
      rows,
      emptyMessage: "No line items in this work package.",
      totalsRow: rows.length ? [null, null, null, null, null, "Subtotal", formatCurrency(wpSubtotalCents / 100)] : null
    });
  }

  if (linesByWp.size === 0) {
    sections.push({
      type: "table",
      heading: "Line Items",
      columns: QUOTE_LINE_COLUMNS,
      rows: [],
      emptyMessage: "No line items recorded for this quotation."
    });
  }

  const preTaxCents = Number.isInteger(quote.pre_tax_total_cents) ? quote.pre_tax_total_cents : Math.round(Number(quote.total_amount || 0) * 100);
  const discountPercent = Number(quote.discount_percent || 0);
  const discountCents = Number.isInteger(quote.discount_cents) ? quote.discount_cents : Math.round(preTaxCents * (discountPercent / 100));
  const netSubtotalCents = Number.isInteger(quote.net_subtotal_cents) ? quote.net_subtotal_cents : Math.max(0, preTaxCents - discountCents);
  const taxTotalCents = Number.isInteger(quote.tax_total_cents) ? quote.tax_total_cents : 0;
  const grandTotalCents = Number.isInteger(quote.grand_total_cents) ? quote.grand_total_cents : (netSubtotalCents + taxTotalCents);

  sections.push({
    type: "keyvalue",
    heading: "Commercial Summary",
    items: [
      { label: "Subtotal (excl. VAT)", value: formatCurrency(preTaxCents / 100) },
      { label: "Grand Total (USD)", value: formatCurrency(grandTotalCents / 100) }
    ]
  });

  const validityDays = quote.validity_days || 30;
  sections.push({
    type: "paragraph",
    heading: "Commercial Terms & Conditions",
    text: `This quotation is valid for ${validityDays} calendar days from the date of issue. All prices are quoted in United States Dollars (USD).`
  });

  sections.push({
    type: "signoff",
    boxes: [
      { label: "Orac Systems — Authorised Signatory" },
      { label: "Client Acceptance — Authorised Signatory" }
    ]
  });

  return {
    documentType: "QUOTATION",
    documentTypeLabel: "Controlled Quotation",
    documentNumber: quote.quote_number || null,
    status: quote.status || "Draft",
    company: {
      name: companyProfile.company_name || FALLBACK_COMPANY.name,
      legalName: companyProfile.legal_name || FALLBACK_COMPANY.legalName
    },
    generatedAtLabel: "Generated",
    generatedAt: humanizeTimestamp(new Date().toISOString()),
    controlledNote: CONTROLLED_NOTE,
    headerMeta: [
      { label: "Client", value: client?.name || "Client" },
      { label: "Validity", value: `${validityDays} days` },
      { label: "Currency", value: "USD" }
    ],
    sections
  };
}

/**
 * Generates a valid controlled PDF Buffer for a quotation.
 */
export function generateQuotePdfBuffer(db, quoteId) {
  const model = buildQuotePdfModel(db, quoteId);
  if (!model) {
    throw Object.assign(new Error(`Quote '${quoteId}' not found`), { status: 404 });
  }
  return generateControlledPdf(model);
}

/**
 * Dispatches a quotation email with the controlled PDF attached.
 */
export async function sendQuotationPdfEmail({
  quoteId,
  recipientEmail,
  recipientName = "",
  subject = null,
  body = null,
  actor,
  store,
  db
}) {
  if (!quoteId) {
    throw Object.assign(new Error("quoteId is required"), { status: 400 });
  }
  if (!recipientEmail) {
    throw Object.assign(new Error("recipientEmail is required"), { status: 400 });
  }

  // 1. Role authorization
  if (actor) {
    requirePermission(actor, "sendQuote");
  }

  // 2. Strict allowlist gating
  if (!isRecipientPermitted(recipientEmail)) {
    throw Object.assign(
      new Error(`Safety Refusal: Recipient '${recipientEmail}' is outside the controlled pilot allowlist. Real delivery is restricted to authorized test accounts.`),
      { status: 403, code: "RECIPIENT_NOT_ALLOWED" }
    );
  }

  // 3. Find quote
  const quote = db.quotes?.find((q) => q.id === quoteId);
  if (!quote) {
    throw Object.assign(new Error(`Quote '${quoteId}' not found`), { status: 404 });
  }

  // 4. Generate real controlled PDF binary
  const pdfBuffer = generateQuotePdfBuffer(db, quoteId);
  const pdfSha256 = crypto.createHash("sha256").update(pdfBuffer).digest("hex");
  const filename = `Quotation-${quote.quote_number || quote.id}.pdf`;

  const emailSubject = subject || `ORAC Quotation ${quote.quote_number || quote.id}`;
  const emailBody = body || `Dear ${recipientName || "Client"},\r\n\r\nPlease find attached quotation ${quote.quote_number || quote.id} from ORAC Industrial Services.\r\n\r\nBest regards,\r\nORAC Commercial Team`;

  // 5. Send email via transport service
  const sendResult = await sendEmail({
    to: recipientEmail,
    toName: recipientName,
    subject: emailSubject,
    body: emailBody,
    attachments: [{
      filename,
      contentType: "application/pdf",
      content: pdfBuffer
    }]
  });

  // 6. Record durable communication evidence
  if (store && db) {
    try {
      recordCommunicationEvidence({
        entityType: "quote",
        entityId: quote.id,
        channel: sendResult.mode === "live-smtp" ? "direct_smtp" : "orac_system_dry_run",
        recipientEmail,
        recipientName,
        subject: emailSubject,
        notes: `[QUOTATION_PDF_DISPATCH] Quotation PDF (${filename}, SHA-256: ${pdfSha256.slice(0, 16)}...) dispatched via ${sendResult.mode}. Provider Message ID: ${sendResult.messageId}.`,
        sentAt: sendResult.timestamp || new Date().toISOString(),
        recordedBy: actor?.id || "system",
        status: sendResult.mode === "live-smtp" ? "delivered" : "dry-run",
        transportMode: sendResult.mode,
        templateVersion: "v1",
        store,
        db
      });
    } catch (_err) {
      // Non-fatal audit recording
    }
  }

  return {
    success: true,
    mode: sendResult.mode,
    messageId: sendResult.messageId,
    quoteId: quote.id,
    quoteNumber: quote.quote_number || quote.id,
    recipientEmail,
    pdfFilename: filename,
    pdfSha256,
    timestamp: sendResult.timestamp
  };
}
