/**
 * Scoped Quotation PDF Email Service
 *
 * Implements the scoped quotation-PDF email dispatch action:
 *  1. Verifies caller role/permission (Admin or Sales).
 *  2. Enforces strict recipient allowlist gating (CONTROLLED_RECIPIENT_ALLOWLIST).
 *  3. Generates the real, controlled quotation PDF buffer via pdfGenerator.js.
 *  4. Writes a write-ahead "send_attempted" evidence row BEFORE any SMTP conversation.
 *  5. Encodes and attaches the PDF to the RFC 5322 MIME message via communicationTransportService.
 *  6. Resolves the evidence row to a truthful status:
 *       accepted        SMTP provider accepted the message (NOT proof of mailbox delivery)
 *       dry-run         nothing was transmitted
 *       send_failed     definitive failure, nothing accepted
 *       send_uncertain  failure after DATA was sent; the message MAY have been accepted
 *  7. Recipient receipt is a SEPARATE, human-recorded evidence action
 *     (confirmQuotationReceipt): who, when, and how receipt was known.
 *
 * SMTP cannot be rolled back, so ordering matters: anything that can be refused is
 * refused (and audited) BEFORE sending; anything that fails AFTER sending is reported
 * loudly and blocks an automatic re-send.
 */

import crypto from "node:crypto";
import { roles, requirePermission } from "../permissions.js";
import { generateControlledPdf, humanizeTimestamp, formatCurrency } from "../pdfGenerator.js";
import { sendEmail, isRecipientPermitted, getTransportConfig, normalizeEmail } from "./communicationTransportService.js";
import {
  recordSystemCommunicationEvidence,
  transitionCommunicationEvidence,
  sanitizeAuditText
} from "./communicationAuditService.js";

const FALLBACK_COMPANY = { name: "Orac Systems", legalName: "Handon Enterprises (Pvt) Ltd" };
const CONTROLLED_NOTE = "Controlled record generated by Orac-IOS. Not valid if altered outside the system.";

function fromCents(cents) {
  return Number.isInteger(cents) ? cents / 100 : 0;
}

/**
 * Builds the controlled PDF model for a quotation record.
 */
export function buildQuotePdfModel(db, quoteId) {
  const quote = db.quotes?.find((q) => q.id === quoteId);
  if (!quote) return null;

  const client = db.clients?.find((c) => c.id === quote.client_id);
  const lines = db.quote_lines?.filter((l) => l.quotation_id === quote.id) || [];
  const equipment = db.equipment_tags?.find((e) => e.id === quote.equipment_tag_id);
  const companyProfile = db.company_profile || {};

  // Build work package grouped lines
  const workPackages = quote.work_packages || [];
  const wpMap = new Map(workPackages.map((wp) => [wp.id, wp.title || wp.name || wp.id]));

  const linesByWp = new Map();
  for (const line of lines) {
    const wpId = line.work_package_id || "wp_01";
    if (!linesByWp.has(wpId)) linesByWp.set(wpId, []);
    linesByWp.get(wpId).push(line);
  }

  const sections = [];

  // Site Reference
  sections.push({
    type: "keyvalue",
    heading: "Site Reference",
    items: [{ label: "Location", value: client?.name || "Client Site" }]
  });

  if (quote.scope_summary) {
    sections.push({
      type: "paragraph",
      heading: "Scope of Work",
      text: quote.scope_summary
    });
  }

  const QUOTE_LINE_COLUMNS = [
    { label: "Type", weight: 1 },
    { label: "Role / Resource", weight: 1.5 },
    { label: "Description", weight: 3 },
    { label: "Qty", weight: 0.7, align: "right" },
    { label: "UoM", weight: 0.8 },
    { label: "Rate (USD)", weight: 1.2, align: "right" },
    { label: "Total (USD)", weight: 1.2, align: "right" }
  ];

  for (const [wpId, wpLines] of linesByWp) {
    const wpName = wpMap.get(wpId) || wpId;
    const rows = wpLines.map((l) => {
      const unitPrice = Number.isInteger(l.unit_price_cents) ? fromCents(l.unit_price_cents) : Number(l.unit_price || 0);
      const lineTotal = Number.isInteger(l.line_total_cents) ? fromCents(l.line_total_cents) : Number(l.line_total ?? (Number(l.quantity) || 0) * unitPrice);
      return [
        l.cost_type || "material",
        l.resource_role || "-",
        l.description || "",
        String(l.quantity ?? ""),
        l.unit_of_measure || "each",
        formatCurrency(unitPrice),
        formatCurrency(lineTotal)
      ];
    });

    const wpSubtotalCents = wpLines.reduce((sum, l) => {
      if (Number.isInteger(l.line_total_cents)) return sum + l.line_total_cents;
      const unitPrice = Number.isInteger(l.unit_price_cents) ? fromCents(l.unit_price_cents) : Number(l.unit_price || 0);
      const lineTotal = Number(l.line_total ?? (Number(l.quantity) || 0) * unitPrice);
      return sum + Math.round(lineTotal * 100);
    }, 0);

    sections.push({
      type: "table",
      heading: linesByWp.size > 1 ? `Work Package: ${wpName}` : "Line Items",
      columns: QUOTE_LINE_COLUMNS,
      rows,
      emptyMessage: "No line items in this work package.",
      totalsRow: rows.length ? [null, null, null, null, null, "Subtotal", formatCurrency(wpSubtotalCents / 100)] : null
    });
  }

  if (linesByWp.size === 0) {
    sections.push({
      type: "table",
      heading: "Line Items",
      columns: QUOTE_LINE_COLUMNS,
      rows: [],
      emptyMessage: "No line items recorded for this quotation."
    });
  }

  const preTaxCents = Number.isInteger(quote.pre_tax_total_cents) ? quote.pre_tax_total_cents : Math.round(Number(quote.total_amount || 0) * 100);
  const discountPercent = Number(quote.discount_percent || 0);
  const discountCents = Number.isInteger(quote.discount_cents) ? quote.discount_cents : Math.round(preTaxCents * (discountPercent / 100));
  const netSubtotalCents = Number.isInteger(quote.net_subtotal_cents) ? quote.net_subtotal_cents : Math.max(0, preTaxCents - discountCents);
  const taxTotalCents = Number.isInteger(quote.tax_total_cents) ? quote.tax_total_cents : 0;
  const grandTotalCents = Number.isInteger(quote.grand_total_cents) ? quote.grand_total_cents : (netSubtotalCents + taxTotalCents);

  sections.push({
    type: "keyvalue",
    heading: "Commercial Summary",
    items: [
      { label: "Subtotal (excl. VAT)", value: formatCurrency(preTaxCents / 100) },
      { label: "Grand Total (USD)", value: formatCurrency(grandTotalCents / 100) }
    ]
  });

  const validityDays = quote.validity_days || 30;
  sections.push({
    type: "paragraph",
    heading: "Commercial Terms & Conditions",
    text: `This quotation is valid for ${validityDays} calendar days from the date of issue. All prices are quoted in United States Dollars (USD).`
  });

  sections.push({
    type: "signoff",
    boxes: [
      { label: "Orac Systems — Authorised Signatory" },
      { label: "Client Acceptance — Authorised Signatory" }
    ]
  });

  return {
    documentType: "QUOTATION",
    documentTypeLabel: "Controlled Quotation",
    documentNumber: quote.quote_number || null,
    status: quote.status || "Draft",
    company: {
      name: companyProfile.company_name || FALLBACK_COMPANY.name,
      legalName: companyProfile.legal_name || FALLBACK_COMPANY.legalName
    },
    generatedAtLabel: "Generated",
    generatedAt: humanizeTimestamp(new Date().toISOString()),
    controlledNote: CONTROLLED_NOTE,
    headerMeta: [
      { label: "Client", value: client?.name || "Client" },
      { label: "Validity", value: `${validityDays} days` },
      { label: "Currency", value: "USD" }
    ],
    sections
  };
}

/**
 * Generates a valid controlled PDF Buffer for a quotation.
 */
export function generateQuotePdfBuffer(db, quoteId) {
  const model = buildQuotePdfModel(db, quoteId);
  if (!model) {
    throw Object.assign(new Error(`Quote '${quoteId}' not found`), { status: 404 });
  }
  return generateControlledPdf(model);
}

// ── Controlled send: evidence lifecycle, retry and idempotency ─────────

const SEND_KIND = "quotation_pdf";
/** States whose real-world outcome is unknown: they block any further live send. */
const UNRESOLVED_STATES = new Set(["send_attempted", "send_uncertain"]);
/** Evidence ids whose SMTP conversation is running in THIS process right now. */
const inFlightAttempts = new Set();

export const RECEIPT_METHODS = Object.freeze([
  "recipient_reply_email", "phone_call", "in_person", "messaging_app", "read_receipt_notification", "other"
]);

function httpError(status, code, message, data) {
  return Object.assign(new Error(message), { status, code, ...(data ? { data } : {}) });
}

function sha256Hex(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

/** Hash of the quote content the client will see, excluding the generation timestamp. */
function quoteContentHash(model) {
  return sha256Hex(JSON.stringify({
    n: model.documentNumber, s: model.status, h: model.headerMeta, sec: model.sections
  }));
}

function failureSummary(err) {
  return String(err?.message || "unknown error").slice(0, 300);
}

function sendEvidence(db, quoteId) {
  return (db.communication_evidence || []).filter(
    (e) => e.entity_type === "quote" && e.entity_id === quoteId && e.send_kind === SEND_KIND
  );
}

// The transport has a 15-second deadline. A fresh reservation also needs
// time to finish its checkpoint and acquire the next transaction.
const RECOVERY_GRACE_MS = 60_000;

export function resolveQuotationSend({ quoteId, evidenceId, outcome, note, actor, store, db }) {
  if (!actor?.id || actor.role !== roles.ADMIN || actor.is_active === false) {
    throw httpError(403, "MAIL_RECOVERY_ADMIN_REQUIRED", "An active administrator is required.");
  }
  const description = typeof note === "string" ? note.trim() : "";
  if (!["receipt_confirmed", "provider_not_accepted"].includes(outcome) ||
      description.length < 10 || description.length > 500) {
    throw httpError(400, "MAIL_RECOVERY_EVIDENCE_REQUIRED", "Choose a verified outcome and describe the evidence in 10–500 characters.");
  }
  const attempts = sendEvidence(db, quoteId);
  const attempt = attempts.find(e => e.id === evidenceId && e.transport_mode === "live-smtp");
  if (!attempt) throw httpError(404, "SEND_EVIDENCE_NOT_FOUND", "No matching send evidence for this quote.");
  if (!UNRESOLVED_STATES.has(attempt.status) || attempt.recovery || attempts.some(e => e.supersedes === attempt.id)) {
    throw httpError(409, "MAIL_RECOVERY_NOT_OPEN", "This attempt is no longer open for recovery.");
  }
  const reservedAt = Date.parse(attempt.recorded_at);
  if (inFlightAttempts.has(attempt.id) || (attempt.status === "send_attempted" &&
      (!Number.isFinite(reservedAt) || Date.now() - reservedAt < RECOVERY_GRACE_MS))) {
    throw httpError(409, "SEND_IN_PROGRESS", "Wait at least one minute after the original attempt and refresh before resolving it.");
  }
  const recovery = {
    outcome, note: sanitizeAuditText(description), recorded_by: actor.id, recorded_at: new Date().toISOString()
  };
  store.audit(db, actor, "communication_evidence", attempt.id, "QUOTE_EMAIL_RECOVERY_RECORDED",
    null, { quote_id: quoteId, outcome });
  attempt.recovery = recovery;
  return { evidenceId: attempt.id, recovery };
}

/**
 * Dispatches a quotation email with the controlled PDF attached.
 *
 * Retry / idempotency contract (live SMTP only; dry-run never blocks and never replays):
 *  - Every request has an effective idempotency key: the caller's `idempotencyKey`
 *    if given, otherwise a hash of quote id + recipient + subject + body + quote content.
 *  - Same key, earlier attempt `accepted`  -> replayed: returns the original result, sends nothing.
 *  - Any unresolved attempt (`send_attempted` / `send_uncertain`) for the same quote and
 *    recipient -> 409, whatever the key. It is cleared only by an explicit
 *    `resendOf` (that attempt's evidence id) plus a written `resendReason`.
 *  - Earlier attempt `send_failed` (definitive) -> a plain retry is allowed.
 *  - To deliberately send the same quote again after an accepted send, supply a NEW idempotencyKey.
 *
 * `deps.sendEmail` is a test seam only; the HTTP route never passes it.
 */
export async function sendQuotationPdfEmail({
  quoteId,
  recipientEmail,
  recipientName = "",
  subject = null,
  body = null,
  idempotencyKey = null,
  resendOf = null,
  resendReason = null,
  actor,
  store,
  db,
  checkpointWrite,
  deps = {}
}) {
  const transmit = deps.sendEmail || sendEmail;

  if (!quoteId) throw httpError(400, "VALIDATION", "quoteId is required");
  if (!recipientEmail) throw httpError(400, "VALIDATION", "recipientEmail is required");
  if (idempotencyKey !== null && idempotencyKey !== undefined && !/^[A-Za-z0-9_-]{8,128}$/.test(String(idempotencyKey))) {
    throw httpError(400, "INVALID_IDEMPOTENCY_KEY", "idempotency_key must be 8-128 characters of letters, digits, '_' or '-'");
  }

  // 1. Role authorization (an actor is mandatory: evidence must name who sent it)
  if (!actor) throw httpError(401, "ACTOR_REQUIRED", "An authenticated actor is required to send a quotation");
  requirePermission(actor, "sendQuote");

  // 2. Strict allowlist gating (fails closed on a missing, empty or wildcard allowlist)
  if (!isRecipientPermitted(recipientEmail)) {
    throw Object.assign(
      new Error(`Safety Refusal: Recipient '${recipientEmail}' is outside the controlled pilot allowlist. Real delivery is restricted to authorized test accounts.`),
      { status: 403, code: "RECIPIENT_NOT_ALLOWED" }
    );
  }

  // 3. Find quote
  const quote = db?.quotes?.find((q) => q.id === quoteId);
  if (!quote) {
    throw Object.assign(new Error(`Quote '${quoteId}' not found`), { status: 404 });
  }

  // 4. Evidence must be recordable BEFORE we send: SMTP cannot be undone afterwards.
  if (!store || typeof store.audit !== "function") {
    throw httpError(500, "COMMUNICATION_AUDIT_UNAVAILABLE", "Audit store unavailable. Nothing was sent.");
  }

  // 5. Generate real controlled PDF binary (synchronous: no await between the guards
  //    below and the intent write, so concurrent identical requests cannot interleave)
  const model = buildQuotePdfModel(db, quoteId);
  const pdfBuffer = generateControlledPdf(model);
  const pdfSha256 = sha256Hex(pdfBuffer);
  const filename = `Quotation-${quote.quote_number || quote.id}.pdf`;

  const emailSubject = subject || `ORAC Quotation ${quote.quote_number || quote.id}`;
  const emailBody = body || `Dear ${recipientName || "Client"},\r\n\r\nPlease find attached quotation ${quote.quote_number || quote.id} from ORAC Industrial Services.\r\n\r\nBest regards,\r\nORAC Commercial Team`;

  const live = !getTransportConfig().dryRun;
  if (live && !deps.sendEmail && typeof checkpointWrite !== "function") {
    throw httpError(503, "SEND_RESERVATION_UNAVAILABLE", "Mail reservation storage is unavailable. Nothing was sent.");
  }
  const recipientNorm = normalizeEmail(recipientEmail);
  const effectiveKey = idempotencyKey
    ? `client:${idempotencyKey}`
    : `auto:${sha256Hex([emailSubject, emailBody, quoteContentHash(model)].join("\u0000"))}`;
  const keyHash = sha256Hex(["quote-email-v1", quote.id, recipientNorm, effectiveKey].join("|"));

  // 6. Retry / idempotency guards (live only)
  const liveAttempts = sendEvidence(db, quote.id).filter(
    (e) => e.transport_mode === "live-smtp" && normalizeEmail(e.recipient_email) === recipientNorm
  );
  let supersedes = null;
  let attemptNumber = 1;
  if (live) {
    const accepted = liveAttempts.filter((e) => e.idempotency_key_hash === keyHash && e.status === "accepted").at(-1);
    if (accepted) return replayResult(accepted, quote);

    const unresolved = liveAttempts.filter(
      (e) => UNRESOLVED_STATES.has(e.status) && !liveAttempts.some((o) => o.supersedes === e.id)
    );
    if (resendOf) {
      const target = unresolved.find((e) => e.id === resendOf);
      if (!target) {
        throw httpError(400, "RESEND_TARGET_INVALID",
          "resend_of must be the evidence id of an unresolved (uncertain or interrupted) attempt for this quote and recipient. To send again after an accepted send, use a new idempotency_key.");
      }
      if (inFlightAttempts.has(target.id)) {
        throw httpError(409, "SEND_IN_PROGRESS", "That send is still in progress; wait for its outcome before re-sending.", { evidenceId: target.id, status: target.status });
      }
      if (target.recovery?.outcome === "receipt_confirmed") {
        throw httpError(409, "MAIL_RECOVERY_RECEIPT_CONFIRMED", "Receipt was confirmed. This attempt cannot be resent.");
      }
      if (checkpointWrite && (target.recovery?.outcome !== "provider_not_accepted" || actor.role !== roles.ADMIN)) {
        throw httpError(403, "MAIL_RECOVERY_ADMIN_REQUIRED", "An administrator must record verified non-acceptance before resending.");
      }
      if (target.status === "send_attempted" && target.recovery?.outcome !== "provider_not_accepted") {
        throw httpError(409, "SEND_RESERVATION_REQUIRES_REVIEW",
          "This send may still be in progress or may have been interrupted. An administrator must reconcile it before any resend.",
          { evidenceId: target.id, status: target.status });
      }
      if (unresolved.some(e => e.id !== target.id)) {
        throw httpError(409, "SEND_OUTCOME_UNRESOLVED", "Resolve the other open attempts for this recipient before resending.");
      }
      if (typeof resendReason !== "string" || resendReason.trim().length < 10) {
        throw httpError(400, "RESEND_REASON_REQUIRED", "resend_reason (at least 10 characters) is required to re-send after an uncertain attempt");
      }
      supersedes = target.id;
    } else if (unresolved.length > 0) {
      const blocker = unresolved[0];
      if (blocker.recovery?.outcome === "receipt_confirmed") {
        throw httpError(409, "MAIL_RECOVERY_RECEIPT_CONFIRMED", "Receipt was confirmed. No new email was sent.");
      }
      const inProgress = inFlightAttempts.has(blocker.id);
      throw httpError(409, inProgress ? "SEND_IN_PROGRESS" : "SEND_OUTCOME_UNRESOLVED",
        inProgress
          ? "A send for this quote and recipient is already in progress. Nothing new was sent."
          : "An earlier send for this quote and recipient has an unknown outcome: the email may already have reached the recipient. Nothing new was sent. Check the sent mailbox, then re-send deliberately with resend_of and resend_reason if needed.",
        { evidenceId: blocker.id, status: blocker.status });
    }
    attemptNumber = Math.max(0, ...liveAttempts.filter((e) => e.idempotency_key_hash === keyHash).map((e) => e.attempt_number || 1)) + 1;
  }

  // 7. Write-ahead intent. If it cannot be recorded, nothing is sent.
  const recordedBy = actor.id || "system";
  let row;
  try {
    row = recordSystemCommunicationEvidence({
      entityType: "quote",
      entityId: quote.id,
      channel: live ? "direct_smtp" : "orac_system_dry_run",
      recipientEmail,
      recipientName,
      subject: emailSubject,
      notes: `[QUOTATION_PDF_DISPATCH] Send attempt started for ${filename} (SHA-256: ${pdfSha256.slice(0, 16)}...). Outcome not yet known.`,
      sentAt: null,
      recordedBy,
      status: "send_attempted",
      transportMode: live ? "live-smtp" : "dry-run",
      templateVersion: "v1",
      extra: {
        send_kind: SEND_KIND, attempt_number: attemptNumber, idempotency_key_hash: keyHash,
        pdf_sha256: pdfSha256, pdf_filename: filename,
        ...(supersedes ? { supersedes, resend_reason: resendReason.trim().slice(0, 300) } : {})
      },
      auditAction: "QUOTE_EMAIL_SEND_ATTEMPTED",
      store,
      db
    });
  } catch (err) {
    throw httpError(503, "AUDIT_UNAVAILABLE_NOT_SENT", `The send could not be recorded, so it was NOT sent. (${failureSummary(err)})`);
  }

  // 8. Transmit
  if (live && checkpointWrite) {
    try {
      db = await checkpointWrite();
      const savedRow = sendEvidence(db, quote.id).find((entry) => entry.id === row.id);
      if (savedRow?.status !== "send_attempted" || savedRow.recovery) {
        throw new Error("Saved reservation is unavailable.");
      }
      row = savedRow;
    } catch {
      throw httpError(503, "SEND_RESERVATION_UNAVAILABLE", "The reservation could not be verified. Nothing was sent by this request.");
    }
  }
  inFlightAttempts.add(row.id);
  let sendResult;
  try {
    sendResult = await transmit({
      to: recipientEmail,
      toName: recipientName,
      subject: emailSubject,
      body: emailBody,
      attachments: [{ filename, contentType: "application/pdf", content: pdfBuffer }]
    });
  } catch (err) {
    inFlightAttempts.delete(row.id);
    // Unknown is not "failed": an untagged error with no HTTP status is treated as uncertain.
    const uncertain = live && (err?.outcomeUncertain === true || (err?.outcomeUncertain === undefined && err?.status === undefined));
    let auditGap = false;
    try {
      transitionCommunicationEvidence({
        evidence: row,
        toStatus: uncertain ? "send_uncertain" : "send_failed",
        patch: {
          failure_reason: failureSummary(err),
          notes: uncertain
            ? `[QUOTATION_PDF_DISPATCH] Outcome UNKNOWN: the connection failed after the message was sent to the provider. It may or may not have been accepted. Do not re-send until the sent mailbox has been checked.`
            : `[QUOTATION_PDF_DISPATCH] Send failed; the provider did not accept the message.`
        },
        actorId: recordedBy,
        auditAction: uncertain ? "QUOTE_EMAIL_SEND_UNCERTAIN" : "QUOTE_EMAIL_SEND_FAILED",
        store,
        db
      });
    } catch (_auditErr) {
      auditGap = true;
      row.audit_gap = "audit write failed while recording the send outcome";
    }
    if (uncertain) {
      throw Object.assign(httpError(502, "SEND_OUTCOME_UNCERTAIN",
        "The mail server did not confirm this message and it may or may not have been sent. Do NOT send it again yet: check the sent mailbox first. Re-sending requires resend_of and resend_reason.",
        { evidenceId: row.id, status: row.status, auditGap }), { saveSendOutcome: !auditGap });
    }
    // Provider error text can echo credentials; never hand it back to the API caller raw.
    err.message = sanitizeAuditText(err.message);
    err.evidenceId = row.id;
    err.auditGap = auditGap;
    err.saveSendOutcome = !auditGap;
    throw err;
  }
  inFlightAttempts.delete(row.id);

  // 9. Resolve the evidence. An audit failure here must NEVER read as a clean success.
  const isLive = sendResult.mode === "live-smtp";
  const acceptedAt = sendResult.timestamp || new Date().toISOString();
  try {
    transitionCommunicationEvidence({
      evidence: row,
      toStatus: isLive ? "accepted" : "dry-run",
      patch: {
        // The transport result is the source of truth for what actually happened.
        transport_mode: isLive ? "live-smtp" : "dry-run",
        channel: isLive ? "direct_smtp" : "orac_system_dry_run",
        sent_at: acceptedAt,
        accepted_at: isLive ? acceptedAt : null,
        message_id_header: sendResult.messageId || null,
        notes: isLive
          ? `[QUOTATION_PDF_DISPATCH] Quotation PDF (${filename}, SHA-256: ${pdfSha256.slice(0, 16)}...) accepted by the SMTP provider (live-smtp). Message-ID header (ORAC-assigned): ${sendResult.messageId}. Provider acceptance only; recipient receipt is not confirmed.`
          : `[QUOTATION_PDF_DISPATCH] Quotation PDF (${filename}, SHA-256: ${pdfSha256.slice(0, 16)}...) recorded in dry-run; no email was transmitted. Message-ID header (ORAC-assigned): ${sendResult.messageId}.`
      },
      actorId: recordedBy,
      auditAction: isLive ? "QUOTE_EMAIL_SEND_ACCEPTED" : "QUOTE_EMAIL_DRY_RUN_RECORDED",
      store,
      db
    });
  } catch (auditErr) {
    row.audit_gap = "audit write failed after the provider accepted the message";
    throw auditGapError(row, quote, isLive);
  }

  return sendResultFromRow(row, quote, false);
}

function auditGapError(row, quote, isLive) {
  return httpError(500, "AUDIT_FAILED_AFTER_ACCEPT",
    isLive
      ? "The email WAS accepted by the mail server, but ORAC could not record the audit trail. Do NOT send it again. Tell an administrator and quote the evidence id."
      : "Dry-run completed (no email was transmitted) but ORAC could not record the audit trail.",
    {
      evidenceId: row.id, status: row.status, accepted: isLive, traceable: false,
      quoteId: quote.id, messageId: row.message_id_header, pdfSha256: row.pdf_sha256
    });
}

function sendResultFromRow(row, quote, replayed) {
  const isLive = row.transport_mode === "live-smtp";
  return {
    success: true,
    status: isLive ? "accepted" : "dry_run",
    mode: row.transport_mode,
    messageId: row.message_id_header,
    quoteId: quote.id,
    quoteNumber: quote.quote_number || quote.id,
    recipientEmail: row.recipient_email,
    pdfFilename: row.pdf_filename,
    pdfSha256: row.pdf_sha256,
    timestamp: row.sent_at,
    evidenceId: row.id,
    replayed,
    recipientReceipt: "not_recorded",
    note: isLive
      ? "The mail server accepted the message. Mailbox delivery and reading are not confirmed; a person must record receipt separately."
      : "Dry-run: no email was transmitted."
  };
}

function replayResult(row, quote) {
  if (row.audit_gap) throw auditGapError(row, quote, true);
  return sendResultFromRow(row, quote, true);
}

// ── Human-recorded recipient receipt ──────────────────────────────────

/**
 * Records that a PERSON learned the recipient received an accepted quotation email.
 * Separate evidence row (status "receipt_confirmed") linked to the send row, which keeps
 * its truthful "accepted" status. Records who confirmed, when (server clock), how receipt
 * was known, and optionally when the recipient says they received it.
 * Only an `accepted` live send can be confirmed; one receipt per send.
 */
export function confirmQuotationReceipt({
  quoteId, evidenceId, method, note = "", receivedAt = null, actor, store, db
}) {
  if (!quoteId) throw httpError(400, "VALIDATION", "quoteId is required");
  if (!evidenceId) throw httpError(400, "VALIDATION", "evidenceId is required");
  if (!actor) throw httpError(401, "ACTOR_REQUIRED", "An authenticated actor is required to record receipt");
  requirePermission(actor, "sendQuote");

  if (!RECEIPT_METHODS.includes(method)) {
    throw httpError(400, "RECEIPT_METHOD_INVALID", `method must be one of: ${RECEIPT_METHODS.join(", ")}`);
  }
  const cleanNote = typeof note === "string" ? note.trim() : "";
  if (cleanNote.length > 500) throw httpError(400, "VALIDATION", "note must be 500 characters or fewer");
  if (method === "other" && cleanNote.length < 5) {
    throw httpError(400, "RECEIPT_NOTE_REQUIRED", "A note describing how receipt was known is required when method is 'other'");
  }

  const send = sendEvidence(db, quoteId).find((e) => e.id === evidenceId);
  if (!send) throw httpError(404, "SEND_EVIDENCE_NOT_FOUND", "No matching send evidence for this quote");
  if (send.status !== "accepted" || send.transport_mode !== "live-smtp") {
    throw httpError(409, "RECEIPT_REQUIRES_ACCEPTED_SEND",
      `Receipt can only be recorded for a send the mail server accepted (this one is '${send.status}').`,
      { evidenceId: send.id, status: send.status });
  }
  const existing = (db.communication_evidence || []).find(
    (e) => e.status === "receipt_confirmed" && e.related_evidence_id === send.id
  );
  if (existing) {
    throw httpError(409, "RECEIPT_ALREADY_RECORDED", "Receipt has already been recorded for this send.", { evidenceId: existing.id });
  }

  let reportedAt = null;
  if (receivedAt !== null && receivedAt !== undefined && receivedAt !== "") {
    const t = Date.parse(receivedAt);
    if (Number.isNaN(t)) throw httpError(400, "RECEIVED_AT_INVALID", "received_at must be an ISO date-time");
    if (t > Date.now() + 5 * 60 * 1000) throw httpError(400, "RECEIVED_AT_INVALID", "received_at cannot be in the future");
    if (send.accepted_at && t < Date.parse(send.accepted_at)) {
      throw httpError(400, "RECEIVED_AT_INVALID", "received_at cannot be before the provider accepted the message");
    }
    reportedAt = new Date(t).toISOString();
  }

  const confirmedAt = new Date().toISOString();
  let receipt;
  try {
    receipt = recordSystemCommunicationEvidence({
      entityType: "quote",
      entityId: quoteId,
      channel: "other",
      recipientEmail: send.recipient_email,
      recipientName: send.recipient_name,
      subject: send.subject,
      notes: `[RECEIPT_CONFIRMED] Recorded by a person (${method}). ${cleanNote}`.trim(),
      sentAt: reportedAt || confirmedAt,
      recordedBy: actor.id || "system",
      status: "receipt_confirmed",
      transportMode: "human-recorded",
      templateVersion: "v1",
      extra: {
        send_kind: "quotation_pdf_receipt", related_evidence_id: send.id, receipt_method: method,
        receipt_reported_at: reportedAt, confirmed_by: actor.id || "system", confirmed_at: confirmedAt
      },
      auditAction: "QUOTE_EMAIL_RECEIPT_CONFIRMED",
      store,
      db
    });
  } catch (err) {
    // Nothing irreversible happened and the row was rolled back: safe to retry.
    throw httpError(500, "COMMUNICATION_AUDIT_FAILED", `Receipt was NOT recorded because the audit write failed; try again. (${failureSummary(err)})`);
  }

  return {
    success: true,
    status: "receipt_confirmed",
    evidenceId: receipt.id,
    sendEvidenceId: send.id,
    quoteId,
    method,
    confirmedBy: receipt.confirmed_by,
    confirmedAt: receipt.confirmed_at,
    receivedAt: receipt.receipt_reported_at
  };
}
